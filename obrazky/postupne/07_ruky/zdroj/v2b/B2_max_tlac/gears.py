"""B2 (max print): printed straight bevel pair - geometry search + tooth strength.

Method
  * Tredgold virtual spur gear: z_v = z / cos(delta), module = mean module m_m = m (1 - 0.5 b / R).
  * Tooth form generated numerically by a basic rack (pressure angle alpha, addendum (1 + x) m, dedendum (1.25 - x) m,
    rack tip radius rho = 0.38 m -> full root fillet) rolled over the virtual gear (raster simulation, 2-D).
  * Lewis form factor from the generated tooth: load at the tip along the line of action, section width t(y) across the
    tooth, Y = min_y t(y)^2 / (6 l(y) m)  (inscribed-parabola criterion), sigma = Ft / (b m_m Y).
  * Dolan-Broghamer fillet factor Kf (AGMA) reported separately (conservative short-term check).
  * Envelope limits for the NOVA left shoulder (frame B, apex O = (39, 3, -17)):
      pinion crown radius <= 4.70 (pan/lift sweep r 33.4 about Z + 1.0 mm; vertical axis 39.115 from Z),
      gear crown radius <= 6.9 (plug cavity r 7.3, plug screw holes at r 9.0, D2.2),
      ratio 1.0 .. 1.67 (servo 300 deg must give the arm >= 180 deg).
writes gears.json
"""
import math, json, sys, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ALLOW = 8.5      # MPa, project long-term allowable (Elegoo Tough)
UTS = 32.1       # MPa, Elegoo Tough tensile (Amazon.de listing, +-10 %, unverified)


_CACHE = {}


def rack_tooth(zv, alpha_deg, x=0.0, rho_f=0.38, hf=1.25, ha=1.0, n=280, nroll=240):
    """one tooth (module 1) of a spur gear with z_v teeth generated by a basic rack (Cartesian raster, tooth centre line
    = +Y, gear centre at the origin).  rack: half width p/4 at the reference line, flank angle alpha, tip line hf below the
    reference line with a tip radius rho_f (full fillet for rho_f 0.38, alpha 20)."""
    al = math.radians(alpha_deg); ta = math.tan(al)
    r = zv / 2.0; ra = r + ha + x; rf = r - hf + x
    p = math.pi
    w = ra * math.sin(math.pi / zv) * 1.05
    xs = np.linspace(-w, w, n); ys = np.linspace(rf - 0.25, ra + 0.02, n)
    X, Y = np.meshgrid(xs, ys)
    mat = (X * X + Y * Y) <= ra * ra
    hc = hf
    vc = -hc + rho_f
    uc = p / 4 + vc * ta - rho_f / math.cos(al)
    vt = vc - rho_f * math.sin(al)
    removed = np.zeros_like(mat)
    for ph in np.linspace(-1.3 * 2 * math.pi / zv, 1.3 * 2 * math.pi / zv, nroll):
        c, s = math.cos(ph), math.sin(ph)
        Xw = c * X - s * Y; Yw = s * X + c * Y
        u = Xw + r * ph
        v = Yw - r - x
        du = np.abs(np.mod(u, p) - p / 2.0)          # distance to the nearest rack tooth centre (teeth at p/2 + k p)
        flank = (v >= vt) & (du <= p / 4 + v * ta)
        tipz = (v < vt) & (v >= -hc)
        arc = tipz & (du <= uc + np.sqrt(np.maximum(rho_f ** 2 - (v - vc) ** 2, 0.0)))
        removed |= flank | arc
    mat &= ~removed
    return dict(mat=mat, xs=xs, ys=ys, r=r, ra=ra, rf=rf)


def lewis_Y(zv, alpha_deg, x=0.0):
    key = (round(zv * 2) / 2, alpha_deg, x)
    if key in _CACHE:
        return _CACHE[key]
    zv = key[0]
    g = rack_tooth(zv, alpha_deg, x)
    mat, xs, ys = g["mat"], g["xs"], g["ys"]
    r, ra = g["r"], g["ra"]
    al = math.radians(alpha_deg)
    ic = len(xs) // 2
    dx = xs[1] - xs[0]
    # contiguous material run containing the centre column, per row
    t = np.zeros(len(ys)); xr = np.zeros(len(ys))
    for i in range(len(ys)):
        row = mat[i]
        if not row[ic]:
            continue
        a = ic
        while a > 0 and row[a - 1]: a -= 1
        b = ic
        while b < len(xs) - 1 and row[b + 1]: b += 1
        t[i] = (b - a + 1) * dx; xr[i] = xs[b] + dx / 2
    itip = np.nonzero(t > 0)[0].max()
    s_tip = t[itip]
    xt, yt = xr[itip], ys[itip]
    rt = math.hypot(xt, yt)
    rb = r * math.cos(al)
    alpha_a = math.acos(min(1.0, rb / rt))
    half = math.atan2(xt, yt)
    yL = yt - xt * math.tan(alpha_a - half)
    best = (1e9, 0, 0, 0)
    for i in range(len(ys)):
        if t[i] <= 0 or ys[i] >= yL - 0.02:
            continue
        if t[i] > 2.5:          # rim (below the space bottom)
            continue
        l = yL - ys[i]
        val = t[i] ** 2 / (6.0 * l)
        if val < best[0]:
            best = (val, t[i], l, ys[i])
    Yf, tc, l, yc = best
    phi = al
    H, Lx, M = 0.34 - 0.4583662 * phi, 0.316 - 0.4583662 * phi, 0.29 + 0.4583662 * phi
    rfil = 0.38 + 0.0
    Kf = H + (tc / rfil) ** Lx * (tc / l) ** M
    # undercut: involute must start at or below the rack tip-line contact (classic limit z_min = 2 (1 - x) / sin^2 alpha)
    zmin = 2 * (1.0 - x) / math.sin(al) ** 2
    out = dict(Y=round(Yf, 4), t_crit=round(tc, 3), l=round(l, 3), Kf=round(Kf, 3), s_tip_over_m=round(s_tip, 3),
               undercut=bool(zv < zmin), zv_min_no_undercut=round(zmin, 1))
    _CACHE[key] = out
    return out


def bevel(m, z1, z2, b, alpha=20.0, x1=0.0, x2=None):
    if x2 is None:
        x2 = -x1
    d1 = math.atan2(z1, z2); d2 = math.pi / 2 - d1
    r1, r2 = m * z1 / 2, m * z2 / 2
    Re = math.hypot(r1, r2)
    f = 1 - 0.5 * b / Re
    mm = m * f
    zv1, zv2 = z1 / math.cos(d1), z2 / math.cos(d2)
    L1 = lewis_Y(zv1, alpha, x1); L2 = lewis_Y(zv2, alpha, x2)
    ha1, ha2 = (1 + x1) * m, (1 + x2) * m
    hf1, hf2 = (1.25 - x1) * m, (1.25 - x2) * m
    crown1 = r1 + ha1 * math.cos(d1); crown2 = r2 + ha2 * math.cos(d2)
    rm2 = r2 * f
    # torque at the ARM (gear) giving ALLOW in the weaker member (Lewis, no Kf)
    Ft_allow = min(ALLOW * b * mm * L1["Y"], ALLOW * b * mm * L2["Y"])
    T_allow = Ft_allow * rm2 / 1000.0
    # contact ratio of the virtual spur pair (mean section)
    al = math.radians(alpha)
    rv1, rv2 = zv1 * mm / 2, zv2 * mm / 2
    rva1, rva2 = rv1 + (1 + x1) * mm, rv2 + (1 + x2) * mm
    rvb1, rvb2 = rv1 * math.cos(al), rv2 * math.cos(al)
    a_v = rv1 + rv2 + (x1 + x2) * mm
    eps = (math.sqrt(rva1 ** 2 - rvb1 ** 2) + math.sqrt(rva2 ** 2 - rvb2 ** 2) - a_v * math.sin(al)) / (math.pi * mm * math.cos(al))
    return dict(m=m, z1=z1, z2=z2, b=b, alpha=alpha, x1=x1, x2=x2, ratio=round(z2 / z1, 3), delta1=round(math.degrees(d1), 2),
                delta2=round(math.degrees(d2), 2), d1=round(2 * r1, 3), d2=round(2 * r2, 3), Re=round(Re, 3),
                b_over_R=round(b / Re, 3), m_mean=round(mm, 4), rm2=round(rm2, 3), zv1=round(zv1, 2), zv2=round(zv2, 2),
                crown1=round(crown1, 3), crown2=round(crown2, 3), Y1=L1, Y2=L2, eps=round(eps, 3),
                T_arm_at_allow=round(T_allow, 4))


def stress(bv, T_arm):
    """Lewis root stress (pinion, gear) and with Kf at an arm torque T_arm (N.m)"""
    Ft = T_arm * 1000.0 / bv["rm2"]
    s1 = Ft / (bv["b"] * bv["m_mean"] * bv["Y1"]["Y"]); s2 = Ft / (bv["b"] * bv["m_mean"] * bv["Y2"]["Y"])
    return dict(Ft=round(Ft, 3), s1=round(s1, 2), s2=round(s2, 2), s1_Kf=round(s1 * bv["Y1"]["Kf"], 2),
                s2_Kf=round(s2 * bv["Y2"]["Kf"], 2))


